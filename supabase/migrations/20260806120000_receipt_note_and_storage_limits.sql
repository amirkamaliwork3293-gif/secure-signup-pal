-- ۱) جایگزین متنی رسید پرداخت: اگر کاربر نتوانست/نخواست عکس رسید آپلود کند،
--    کد پیگیری و تاریخ واریز را به‌صورت متن وارد می‌کند و مدیر بر همان اساس
--    تایید/رد می‌کند. nullable است تا هیچ رکورد قبلی نشکند.
ALTER TABLE public.signup_requests
  ADD COLUMN IF NOT EXISTS receipt_note text;

-- ۲) خط دفاعی سمت سرور روی باکت‌های استوریج (سقف حجم فایل).
--    محدودیت‌های سمت مرورگر قابل دور زدن هستند؛ این‌ها نیستند.
--    اگر باکتی وجود نداشته باشد، UPDATE بی‌اثر است (خطا نمی‌دهد).

-- رسید پرداخت: بعد از فشرده‌سازی معمولاً زیر ۱ مگابایت است.
UPDATE storage.buckets SET file_size_limit = 5 * 1024 * 1024 WHERE id = 'receipts';

-- رسانه‌ی صفحه‌ی معرفی: فقط عکس. آپلود فایل ویدیو عمداً مسدود است — ویدیو باید
-- از آپارات/یوتیوب (iframe) پخش شود. ویدیوهای قدیمیِ موجود در باکت دست‌نخورده
-- می‌مانند؛ این محدودیت فقط روی آپلودهای جدید اثر دارد.
UPDATE storage.buckets
SET file_size_limit = 10 * 1024 * 1024,
    allowed_mime_types = ARRAY[
      'image/jpeg', 'image/png', 'image/webp', 'image/gif', 'image/heic', 'image/heif'
    ]
WHERE id = 'landing-media';

-- لوگو/نمونه‌کار فروشگاه و عکس‌های منو: همه از مسیر فشرده‌سازی استاندارد می‌آیند.
UPDATE storage.buckets SET file_size_limit = 5 * 1024 * 1024
WHERE id IN ('store-assets', 'menu-images');
